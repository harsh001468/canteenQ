// 7. Realistic 30-Day Historical Order Log Sample (for CSV ingestion & ML demonstration)
export function generateSampleHistoricalLogs(): HistoricalLog[] {
  const items = [
    'Samosa', 'Special Cutting Chai', 'Filter Coffee', 'Paneer Grilled Sandwich',
    'Butter Masala Maggi', 'Veggie Crunch Burger', 'Cold Coffee with Ice Cream',
    'Indori Poha with Sev', 'Steamed Veg Momos', 'Cheesy Pizza Slice', 'Cold Drinks'
  ];
  const logs: HistoricalLog[] = [];
  const days = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];

  // Seed sample logs
  for (let i = 1; i <= 240; i++) {
    const day = days[i % days.length];
    const hour = 9 + (i % 8); // 9 to 16
    const wasBreak = hour === 10 || hour === 12 || hour === 14;
    const item = items[i % items.length];
    const qty = wasBreak ? Math.floor(Math.random() * 3) + 2 : 1;
    const dayOffset = Math.floor(i / 10);
    const dateStr = `2026-10-${String(27 - (dayOffset % 26)).padStart(2, '0')}`;
    const minStr = String(Math.floor(Math.random() * 59)).padStart(2, '0');

    logs.push({
      timestamp: `${dateStr} ${String(hour).padStart(2, '0')}:${minStr}`,
      item,
      quantity: qty,
      order_id: `CQ-H${1000 + i}`,
      day_of_week: day,
      hour,
      was_break: wasBreak,
    });
  }
  return logs;
}

